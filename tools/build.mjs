import { readdir, readFile, writeFile, mkdir, rm, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
async function files(dir) {
  const entries = await readdir(path.join(root, dir), { withFileTypes: true });
  const groups = await Promise.all(entries.filter(e => !e.name.startsWith('.')).map(e => e.isDirectory() ? files(path.posix.join(dir, e.name)) : [path.posix.join(dir, e.name)]));
  return groups.flat();
}
const entries = (await readdir(root)).filter(f => /\.(js|css|html|webmanifest)$/.test(f) && f !== 'build.js');
const assets = [...entries, ...await files('engine'), ...await files('prompt'), ...await files('icons')].sort();
const hash = createHash('sha256');
for (const file of assets) { hash.update(file); hash.update(await readFile(path.join(root, file))); }
const build = `m2-${hash.digest('hex').slice(0, 12)}`;
await writeFile(path.join(root, 'build.js'), `// Generated by tools/build.mjs\nexport const BUILD = '${build}';\nexport const ASSETS = ${JSON.stringify(['./', './build.js', ...assets.filter(f => f !== 'sw.js').map(f => './' + f)], null, 2)};\n`);
const output = path.resolve(root, 'dist');
if (path.dirname(output) !== path.resolve(root) || path.basename(output) !== 'dist') throw new Error('Unexpected build output directory');
await rm(output, { recursive: true, force: true });
for (const file of [...assets, 'build.js']) {
  const target = path.join(output, file);
  await mkdir(path.dirname(target), { recursive: true });
  await copyFile(path.join(root, file), target);
}
console.log(`Built ${build}: ${assets.length + 1} application assets`);
